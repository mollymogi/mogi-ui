const { chromium } = require(process.env.MOGI_PLAYWRIGHT_PATH || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, colorScheme: 'light' })
  const page = await context.newPage(), errors = [], checks = []
  const ok = name => checks.push(name)
  page.on('pageerror', error => errors.push(error.message))
  const base = process.env.MOGI_PREVIEW_URL || 'http://127.0.0.1:5193'
  const output = process.env.MOGI_BROWSER_OUTPUT || '/tmp/mogi-pr-workspace'
  fs.mkdirSync(output, { recursive: true })
  await page.goto(base + '/?preview=pr-workspace&theme=paper')
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(250)
  assert.equal(await page.locator('html').getAttribute('data-palette'), 'paper')
  assert.equal(await page.locator('.pr-demo').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 247, 230)')
  assert.equal(await page.getByRole('heading', { name: 'PR 看板 .' }).count(), 1)
  ok('Paper palette renders the PR workspace from the shared tokens')
  await page.locator('.pr-skip').focus(); assert.equal(await page.locator('.pr-skip').evaluate(el => getComputedStyle(el).clipPath), 'none')
  await page.locator('h1').click(); assert.notEqual(await page.locator('.pr-skip').evaluate(el => getComputedStyle(el).clipPath), 'none')
  ok('Skip link appears only while focused')
  const primary = page.getByRole('link', { name: '查看看板' })
  assert.match(await primary.evaluate(el => getComputedStyle(el).boxShadow), /4px 5px/)
  await primary.focus(); await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab')
  assert.equal(await primary.evaluate(el => getComputedStyle(el).outlineWidth), '3px')
  ok('Primary hard shadow and separate visible keyboard focus both render')
  const search = page.getByRole('textbox', { name: '搜索 PR 或项目' })
  await search.fill('日期边界'); assert.equal(await page.locator('.pr-task').count(), 0)
  await search.fill('恢复云端'); assert.equal(await page.locator('.pr-task').count(), 1)
  await search.fill(''); await page.getByLabel('筛选项目').selectOption('atlas')
  assert.equal(await page.locator('.pr-project').count(), 1)
  assert.match(await page.locator('.pr-project-heading').innerText(), /atlas/)
  await page.getByLabel('筛选项目').selectOption('all')
  ok('Search and project selection filter only the current view')
  const heading = page.locator('.pr-project-heading').first()
  await heading.click(); assert.equal(await heading.getAttribute('data-state'), 'closed')
  await heading.focus(); await page.keyboard.press('Enter'); assert.equal(await heading.getAttribute('data-state'), 'open')
  ok('Project groups collapse and expand with pointer and keyboard')
  const detailButton = page.locator('.pr-title').first()
  await detailButton.click(); await page.getByRole('dialog').waitFor()
  assert.equal(await page.getByRole('dialog').getByText('两个会话，各司其职').count(), 1)
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await detailButton.evaluate(el => el === document.activeElement), true)
  ok('Detail sheet preserves independent roles and returns focus after Escape')
  await page.getByRole('tab', { name: '已归档 12' }).click()
  assert.equal(await page.locator('.pr-project').count(), 2)
  assert.equal(await page.locator('.pr-task').count(), 4)
  await page.getByRole('button', { name: '再显示 1 条' }).first().click()
  assert.equal(await page.locator('.pr-task').count(), 5)
  await page.getByRole('button', { name: '下一页' }).click()
  assert.match(await page.locator('.pr-project-heading').first().innerText(), /field-kit/)
  await search.fill('mogi-ui'); assert.equal(await page.locator('.pr-project').count(), 1)
  assert.match(await page.locator('.pr-project-heading').innerText(), /mogi-ui/)
  await search.fill(''); await page.getByRole('tab', { name: '进行中 4' }).click()
  ok('Archive is bounded by project pagination and per-project expansion; filtering resets the page')
  for (const dark of [false, true]) {
    if (dark) await page.getByRole('button', { name: '切换暗色' }).click()
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1080 })
      await page.waitForTimeout(100)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px page overflow`)
      ok(`No horizontal overflow at ${width}px ${dark ? 'dark' : 'paper'}`)
      await page.locator('h1').click(); await page.evaluate(() => scrollTo(0, 0))
      if ([390, 1440].includes(width)) await page.screenshot({ path: `${output}/pr-workspace-${width}-${dark ? 'dark' : 'paper'}.png`, fullPage: true })
    }
    if (dark) assert.equal(await primary.evaluate(el => getComputedStyle(el).boxShadow.includes('4px 5px')), false)
  }
  ok('Dark mode does not retain paper-only button shadows')
  await page.getByRole('button', { name: '切换亮色' }).click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await primary.hover()
  assert.equal(await primary.evaluate(el => getComputedStyle(el).translate), 'none')
  ok('Reduced motion disables tactile button translation')
  await page.goto(base + '/?preview=pr-workspace&theme=light')
  assert.equal(await page.locator('html').getAttribute('data-palette'), null)
  assert.notEqual(await page.locator('.pr-demo').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 247, 230)')
  ok('Base warm theme stays available independently of paper')
  assert.deepEqual(errors, [])
  const result = { browser: await browser.version(), checks, errors }
  fs.writeFileSync(`${output}/pr-workspace-browser.json`, JSON.stringify(result, null, 2) + '\n')
  console.log(JSON.stringify({ passed: checks.length, errors }))
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
